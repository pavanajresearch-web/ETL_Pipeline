logger = logging.getLogger(__name__)

# 2. Define your 3 file paths in Google Drive [UPDATE THESE PATHS]
file1_path = 'Market_data/kanakapura/cocoon_prices.csv'
file2_path = 'Market_data/ramanagara/cocoon_prices.csv'
file3_path = 'Market_data/kolar/cocoon_prices.csv'

# 3. Load and combine the three files
# Use utf-8-sig to automatically handle any potential BOM (\xef\xbb\xbf) headers
print("\nLoading files from Google Drive...")
df1 = pd.read_csv(file1_path, encoding='utf-8-sig')
df2 = pd.read_csv(file2_path, encoding='utf-8-sig')
df3 = pd.read_csv(file3_path, encoding='utf-8-sig')

# Guardrail: Ensure market column is reliably present and derived from directory path if missing
if 'market' not in df1.columns or df1['market'].isna().all(): df1['market'] = 'kanakapura'
if 'market' not in df2.columns or df2['market'].isna().all(): df2['market'] = 'ramanagara'
if 'market' not in df3.columns or df3['market'].isna().all(): df3['market'] = 'kolar'

"""### Step 1 — Combine Three Datasets"""

print(f"Shape of df1: {df1.shape}")
print(f"Shape of df2: {df2.shape}")
print(f"Shape of df3: {df3.shape}")

combined_df = pd.concat([df1, df2, df3], ignore_index=True)
print(f"Shape of combined_df: {combined_df.shape}")

# String standardization: Unicode NFKC normalization and hidden whitespace/control character cleaning
def sanitize_text(val):
    if pd.isna(val):
        return ""
    norm = unicodedata.normalize('NFKC', str(val)).strip()
    return re.sub(r'[\r\n\t]+', ' ', norm).strip()

for col in ['market', 'variety']:
    if col in combined_df.columns:
        combined_df[col] = combined_df[col].apply(sanitize_text)

combined_df['market'] = combined_df['market'].str.lower()
combined_df['variety'] = combined_df['variety'].str.upper()

"""### Step 2 — Inspect Nulls and Data Types"""

print("\nNull counts per column:")
print(combined_df.isnull().sum())

print("\nData types of each column:")
print(combined_df.dtypes)

print("\nSample of 5 rows:")
print(combined_df.head())

"""### Step 3 — Extract and Standardize Dates from Source URL"""

def extract_date_from_url(url):
    """
    Extracts and parses a date from a URL string, handling numeric and month name formats.
    Returns a pandas Timestamp object if successful, otherwise pd.NaT.
    """
    if pd.isna(url):
        return pd.NaT
    # Regex handles both 1-2 digit days, numeric months, and full/short month names
    match = re.search(r'market-(\d{1,2}-\d{1,2}-\d{4}|\d{1,2}-[a-zA-Z]+-\d{4})', str(url), re.IGNORECASE)
    if match:
        date_str = match.group(1)
        for fmt in ('%d-%m-%Y', '%d-%B-%Y', '%d-%b-%Y'):
            try:
                return pd.to_datetime(date_str, format=fmt, errors='raise')
            except ValueError:
                continue
    return pd.NaT

# Apply the function to create url_date column
combined_df.loc[:, 'url_date'] = combined_df['source_url'].apply(extract_date_from_url)

successful_url_extractions = combined_df['url_date'].notna().sum()
print(f"Count of rows where url_date was successfully extracted: {successful_url_extractions}")

unresolvable_url_dates = combined_df['url_date'].isna().sum()
print(f"Count of rows where url_date could not be extracted (unresolvable): {unresolvable_url_dates}")

# Impute 'date' column for nulls using 'url_date'
null_date_mask = combined_df['date'].isna()
combined_df.loc[null_date_mask, 'date'] = combined_df.loc[null_date_mask, 'url_date'].dt.strftime('%d-%m-%Y')

print(f"\nNumber of nulls in 'date' column after imputation: {combined_df['date'].isnull().sum()}")

"""### Step 4 — Resolve Date Offsets"""

# 1. Parse 'date' column with dayfirst=True and standardized delimiters
date_str_clean = combined_df['date'].astype(str).str.strip().str.replace('/', '-', regex=False)
date_str_clean = date_str_clean.replace(['nan', 'NaT', 'none', 'None', ''], np.nan)
combined_df['date_parsed'] = pd.to_datetime(date_str_clean, dayfirst=True, errors='coerce')

# If date_parsed is NaT, fallback to url_date
null_parsed_mask = combined_df['date_parsed'].isna() & combined_df['url_date'].notna()
combined_df.loc[null_parsed_mask, 'date_parsed'] = combined_df.loc[null_parsed_mask, 'url_date']

# 2. Compute date_offset_days = date_parsed - url_date in days
combined_df['date_offset_days'] = (combined_df['date_parsed'] - combined_df['url_date']).dt.days

# Initialize 'date_resolved' with a copy of 'date_parsed'
combined_df['date_resolved'] = combined_df['date_parsed']
combined_df['date_correction_applied'] = 'none'
combined_df.loc[null_parsed_mask, 'date_correction_applied'] = 'imputed_from_url'

# 3. Apply resolution rules
combined_df['date_offset_days_recomputed'] = (combined_df['date_resolved'] - combined_df['url_date']).dt.days

# Rule: -365 or -366 -> Replace 'date' with 'url_date' (corrected year bug)
mask_year_bug = combined_df['date_offset_days_recomputed'].isin([-365, -366]) & combined_df['url_date'].notna()
combined_df.loc[mask_year_bug, 'date_resolved'] = combined_df.loc[mask_year_bug, 'url_date']
combined_df.loc[mask_year_bug, 'date_correction_applied'] = 'corrected_year_bug'
# Align effective date_offset_days to 0 for resolved year bugs so they are not dropped by downstream outlier filters
combined_df.loc[mask_year_bug, 'date_offset_days'] = 0.0

# Rule: -1, +1, -2, +2 -> Keep 'date' column as-is (small lag)
mask_small_lag = combined_df['date_offset_days_recomputed'].isin([-2, -1, 1, 2]) & (combined_df['date_correction_applied'] == 'none')
combined_df.loc[mask_small_lag, 'date_correction_applied'] = 'kept_col_small_lag'

# Recompute date_offset_days_recomputed after resolution
combined_df['date_offset_days_recomputed'] = (combined_df['date_resolved'] - combined_df['url_date']).dt.days

# Print value counts of date_correction_applied
print("\nValue counts for date_correction_applied:")
print(combined_df['date_correction_applied'].value_counts())

print(f"\nNumber of nulls in 'date_resolved' after Step 4: {combined_df['date_resolved'].isnull().sum()}")

"""### Step 5 — Flag Price Logic Violations"""

# Convert price columns to numeric
for col in ['min_price', 'avg_price', 'max_price']:
    combined_df[col] = pd.to_numeric(combined_df[col], errors='coerce')

combined_df['flag_price_logic'] = False
combined_df['price_logic_failure_type'] = 'none'

# Condition: min_price <= avg_price <= max_price
mask_violation = ~((combined_df['min_price'] <= combined_df['avg_price']) & (combined_df['avg_price'] <= combined_df['max_price']))
combined_df.loc[mask_violation, 'flag_price_logic'] = True

# Classify each violation type
mask_min_max_swapped = combined_df['min_price'] > combined_df['max_price']
combined_df.loc[mask_min_max_swapped, 'price_logic_failure_type'] = 'min_max_swapped'

mask_other_violations = combined_df['price_logic_failure_type'] == 'none'

mask_avg_below_min_rounding = (combined_df['avg_price'] < combined_df['min_price']) & \
                              ((combined_df['min_price'] - combined_df['avg_price']) <= 2) & \
                              mask_other_violations
combined_df.loc[mask_avg_below_min_rounding, 'price_logic_failure_type'] = 'avg_below_min_rounding'

mask_avg_below_min_large = (combined_df['avg_price'] < combined_df['min_price']) & \
                           ((combined_df['min_price'] - combined_df['avg_price']) > 2) & \
                           mask_other_violations
combined_df.loc[mask_avg_below_min_large, 'price_logic_failure_type'] = 'avg_below_min_large'

mask_avg_above_max_rounding = (combined_df['avg_price'] > combined_df['max_price']) & \
                                ((combined_df['avg_price'] - combined_df['max_price']) <= 2) & \
                                mask_other_violations
combined_df.loc[mask_avg_above_max_rounding, 'price_logic_failure_type'] = 'avg_above_max_rounding'

mask_avg_above_max_large = (combined_df['avg_price'] > combined_df['max_price']) & \
                            ((combined_df['avg_price'] - combined_df['max_price']) > 2) & \
                            mask_other_violations
combined_df.loc[mask_avg_above_max_large, 'price_logic_failure_type'] = 'avg_above_max_large'

print("\nPrice Logic Failure Type Counts:")
print(combined_df['price_logic_failure_type'].value_counts())

flagged_price_logic_rows = combined_df[combined_df['flag_price_logic']].copy()
flagged_price_logic_rows.to_csv('price_logic_review.csv', index=False)
print("\nFlagged price logic rows saved to 'price_logic_review.csv'")

"""### Step 6 — Flag Duplicates"""

duplicate_cols = ['market', 'date_resolved', 'variety']
combined_df['flag_duplicate'] = combined_df.duplicated(subset=duplicate_cols, keep=False)

combined_df['duplicate_price_divergence'] = 0.0
combined_df['duplicate_type'] = 'none'

duplicate_groups = combined_df[combined_df['flag_duplicate']].groupby(duplicate_cols)

for name, group in duplicate_groups:
    max_avg_price = group['avg_price'].max()
    min_avg_price = group['avg_price'].min()
    divergence = max_avg_price - min_avg_price

    combined_df.loc[group.index, 'duplicate_price_divergence'] = divergence

    if divergence > 50:
        combined_df.loc[group.index, 'duplicate_type'] = 'possible_multi_session'
    else:
        combined_df.loc[group.index, 'duplicate_type'] = 'likely_scraper_duplicate'

print("\nFlagged duplicate rows count:")
print(combined_df['flag_duplicate'].sum())

print("\nDuplicate type breakdown:")
print(combined_df['duplicate_type'].value_counts())

flagged_duplicate_rows = combined_df[combined_df['flag_duplicate']].copy()
flagged_duplicate_rows.to_csv('duplicates_review.csv', index=False)
print("\nFlagged duplicate rows saved to 'duplicates_review.csv'")

"""### Step 7 — Encode Categorical Columns"""

# 1. Market: Standardize canonical 'market' column AND generate one-hot dummy columns
combined_df['market'] = combined_df['market'].astype(str).str.strip().str.lower()
for m in ['kanakapura', 'kolar', 'ramanagara']:
    combined_df[f'market_{m}'] = (combined_df['market'] == m).astype(int)

# 2. Variety: Binary encode the `variety` column robustly to integer flag is_BV (1 for BV, 0 for CB)
print("Unique values in 'variety' before encoding:")
print(combined_df['variety'].unique())

def encode_variety(v):
    v = str(v).strip().upper()
    if 'BV' in v or 'BIVOLTINE' in v or 'BI-VOLTINE' in v:
        return 1
    return 0

combined_df['is_BV'] = combined_df['variety'].apply(encode_variety).astype(int)

# Drop original variety column
combined_df = combined_df.drop(columns=['variety'])

print("\nValue counts of 'is_BV' after encoding:")
print(combined_df['is_BV'].value_counts())

"""### Step 7.5 — Resolve remaining `date_resolved` nulls"""

initial_rows = combined_df.shape[0]
combined_df.dropna(subset=['date_resolved'], inplace=True)

dropped_rows = initial_rows - combined_df.shape[0]
print(f"Dropped {dropped_rows} rows due to null 'date_resolved' values.")
print(f"New shape of combined_df: {combined_df.shape}")
print(f"Number of nulls in 'date_resolved' after dropping: {combined_df['date_resolved'].isnull().sum()}")

"""### Step 8 — Final Inspection Report"""

print("\n--- Final Data Inspection Report ---")
