print(combined_df['market_kolar'].value_counts())
print("\n7. Value counts for 'market_kanakapura':")
print(combined_df['market_kanakapura'].value_counts())
print("\n8. Value counts for 'market_ramanagara':")
print(combined_df['market_ramanagara'].value_counts())

"""### Finding Duplicates by Market, `is_BV`, and `date_resolved`"""

duplicate_check_cols = ['market_kanakapura', 'market_kolar', 'market_ramanagara', 'is_BV', 'date_resolved']
combined_df['new_flag_duplicate_market_type_date'] = combined_df.duplicated(subset=duplicate_check_cols, keep=False)
num_new_duplicates = combined_df['new_flag_duplicate_market_type_date'].sum()
print(f"Number of records flagged as duplicate based on (market, is_BV, date_resolved): {num_new_duplicates}")

"""### Resolving Duplicates by Shifting `date_resolved` based on `url_date`"""

unique_combinations_set = set(
    tuple(row) for row in combined_df[~combined_df['new_flag_duplicate_market_type_date']][duplicate_check_cols].values
)

modifications = []
duplicate_indices = combined_df[combined_df['new_flag_duplicate_market_type_date']].index.tolist()
grouped_duplicates_original = combined_df.loc[duplicate_indices].groupby(duplicate_check_cols[:-1])

for name, group_df_original in grouped_duplicates_original:
    group_df = group_df_original.sort_values(by='date_resolved').copy()
    first_row_idx = group_df.index[0]
    ref_date = combined_df.loc[first_row_idx, 'date_resolved']
    market_kanakapura_val, market_kolar_val, market_ramanagara_val, is_BV_val = name

    for i in range(1, len(group_df)):
        current_idx = group_df.index[i]
        current_row_url_date = combined_df.loc[current_idx, 'url_date']
        new_proposed_date = ref_date + pd.Timedelta(days=1)

        if pd.notna(current_row_url_date) and current_row_url_date == new_proposed_date:
            proposed_unique_combo = (market_kanakapura_val, market_kolar_val, market_ramanagara_val, is_BV_val, new_proposed_date)
            if proposed_unique_combo not in unique_combinations_set:
                modifications.append({
                    'index': current_idx,
                    'date_resolved': new_proposed_date,
                    'date_correction_applied': 'shifted_duplicate_date_by_url'
                })
                unique_combinations_set.add(proposed_unique_combo)
                ref_date = new_proposed_date

for mod in modifications:
    combined_df.loc[mod['index'], 'date_resolved'] = mod['date_resolved']
    combined_df.loc[mod['index'], 'date_correction_applied'] = mod['date_correction_applied']

print(f"Applied {len(modifications)} date shifts to resolve duplicates based on url_date next day logic.")

combined_df['new_flag_duplicate_market_type_date_after_shift'] = combined_df.duplicated(subset=duplicate_check_cols, keep=False)
num_remaining_duplicates = combined_df['new_flag_duplicate_market_type_date_after_shift'].sum()
print(f"Number of records remaining as duplicate after shifting: {num_remaining_duplicates}")

